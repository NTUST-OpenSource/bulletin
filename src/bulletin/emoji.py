"""Emoji, which renditions never hold (owner, 2026-11-15)."""

import re

# Unicode's Emoji_Presentation below U+10000 (Unicode 18.0); above it, every emoji lies in the
# block of pictographs from U+1F000 to U+1FAFF, and tag characters build regional flags.
PRESENTED = (
    (0x231A, 0x231B), (0x23E9, 0x23EC), (0x23F0, 0x23F0), (0x23F3, 0x23F3), (0x25FD, 0x25FE),
    (0x2614, 0x2615), (0x2648, 0x2653), (0x267F, 0x267F), (0x2693, 0x2693), (0x26A1, 0x26A1),
    (0x26AA, 0x26AB), (0x26BD, 0x26BE), (0x26C4, 0x26C5), (0x26CE, 0x26CE), (0x26D4, 0x26D4),
    (0x26EA, 0x26EA), (0x26F2, 0x26F3), (0x26F5, 0x26F5), (0x26FA, 0x26FA), (0x26FD, 0x26FD),
    (0x2705, 0x2705), (0x270A, 0x270B), (0x2728, 0x2728), (0x274C, 0x274C), (0x274E, 0x274E),
    (0x2753, 0x2755), (0x2757, 0x2757), (0x2795, 0x2797), (0x27B0, 0x27B0), (0x27BF, 0x27BF),
    (0x2B1B, 0x2B1C), (0x2B50, 0x2B50), (0x2B55, 0x2B55), (0x1F000, 0x1FAFF), (0xE0020, 0xE007F),
)  # fmt: skip
VS16, ZWJ, KEYCAP = chr(0xFE0F), chr(0x200D), chr(0x20E3)
# A keycap keeps its digit; a symbol followed by VS16 asks for emoji presentation and goes too.
KEYCAPS = re.compile(f"([0-9#*]){VS16}?{KEYCAP}")
EMOJI = re.compile(
    "(?:["
    + "".join(f"{chr(first)}-{chr(last)}" for first, last in PRESENTED)
    + f"]|[^\\s]{VS16}|[{VS16}{ZWJ}])+ ?"
)


def strip_emoji(text: str) -> str:
    """`text` without emoji, each with the space after it."""
    return EMOJI.sub("", KEYCAPS.sub(r"\1", text))
